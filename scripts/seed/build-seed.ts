/**
 * Builds supabase/seed/seed.sql from the pre-database sources of truth:
 *   - supabase/seed/placeholder-products.ts  (four placeholder laptops, D-003)
 *   - supabase/seed/candidate-services.ts     (seven candidate services, D-017)
 *   - src/i18n/messages/{en,gu}.json          (category names)
 *   - supabase/seed/candidate-services.copy.json (service copy)
 *
 * Run:  node scripts/seed/build-seed.ts
 *
 * The output is idempotent (ON CONFLICT DO NOTHING keyed on slugs), so it can
 * be re-applied safely and never overwrites anything an admin has edited.
 * Every product row keeps is_placeholder = true and price_is_verified = false;
 * every service keeps is_candidate = true. Nothing is promoted to verified.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

import { placeholderProducts } from "../../supabase/seed/placeholder-products.ts";
import { candidateServices as services } from "../../supabase/seed/candidate-services.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const en = JSON.parse(
  readFileSync(join(root, "src/i18n/messages/en.json"), "utf8"),
);
const gu = JSON.parse(
  readFileSync(join(root, "src/i18n/messages/gu.json"), "utf8"),
);
// Service copy moved out of the message catalogues once it became editable
// in /admin/services; it is kept here only as seed input.
const serviceCopy = JSON.parse(
  readFileSync(
    join(root, "supabase/seed/candidate-services.copy.json"),
    "utf8",
  ),
);

const q = (value: string | null | undefined) =>
  value == null ? "null" : `'${value.replaceAll("'", "''")}'`;
const arr = (values: string[]) => `array[${values.map(q).join(", ")}]::text[]`;
const json = (value: unknown) => `${q(JSON.stringify(value))}::jsonb`;

const categorySlugs = ["laptops", "desktops", "components", "accessories"];

const lines: string[] = [];
lines.push(
  "-- GENERATED by scripts/seed/build-seed.ts. Do not edit by hand.",
  "-- Placeholder catalogue (D-003) and candidate services (D-017).",
  "-- Idempotent: re-running never overwrites rows an admin has edited.",
  "",
  "begin;",
  "",
);

categorySlugs.forEach((slug, i) => {
  lines.push(
    `insert into public.categories (slug, name_en, name_gu, sort_order) values (${q(slug)}, ${q(en.products.categories[slug])}, ${q(gu.products.categories[slug])}, ${i}) on conflict (slug) do nothing;`,
  );
});
lines.push("");

const brands = [...new Set(placeholderProducts.map((p) => p.brand))];
for (const brand of brands) {
  lines.push(
    `insert into public.brands (slug, name) values (${q(brand.toLowerCase())}, ${q(brand)}) on conflict (slug) do nothing;`,
  );
}
lines.push("");

for (const p of placeholderProducts) {
  lines.push(
    `insert into public.products (slug, brand_id, category_id, name, summary_specs, specs, price_paise, price_is_verified, availability, is_new, is_featured, is_placeholder, status)`,
    `select ${q(p.slug)}, b.id, c.id, ${q(p.name)}, ${arr(p.summarySpecs)}, ${json(p.specs)}, ${p.priceInPaise ?? "null"}, false, ${q(p.availability)}, ${p.isNew}, false, true, 'published'`,
    `from public.categories c left join public.brands b on b.slug = ${q(p.brand.toLowerCase())}`,
    `where c.slug = ${q(p.category)}`,
    `on conflict (slug) do nothing;`,
  );
  if (p.image) {
    const img = p.image;
    lines.push(
      `insert into public.product_media (product_id, storage_path, kind, alt_en, sort_order, is_primary, width, height, is_representative, credit)`,
      `select p.id, ${q(img.src)}, 'image', ${q(img.alt)}, 0, true, ${img.width}, ${img.height}, ${img.representative}, ${json(img.credit)}`,
      `from public.products p where p.slug = ${q(p.slug)}`,
      `and not exists (select 1 from public.product_media m where m.product_id = p.id);`,
    );
  }
  lines.push("");
}

services.forEach((s, i) => {
  const e = serviceCopy.en[s.key];
  const g = serviceCopy.gu[s.key];
  lines.push(
    `insert into public.services (slug, key, name_en, name_gu, summary_en, summary_gu, problem_en, problem_gu, covers_en, covers_gu, signs_en, signs_gu, icon, image_path, image_is_photo, sort_order, status, is_candidate)`,
    `values (${q(s.slug)}, ${q(s.key)}, ${q(e.title)}, ${q(g?.title)}, ${q(e.summary)}, ${q(g?.summary)}, ${q(e.problem)}, ${q(g?.problem)}, ${arr(e.covers)}, ${arr(g?.covers ?? [])}, ${arr(e.signs)}, ${arr(g?.signs ?? [])}, ${q(s.key)}, ${q(s.image)}, ${s.photo}, ${i}, 'published', true)`,
    `on conflict (slug) do nothing;`,
    "",
  );
});

lines.push("commit;", "");

const out = join(root, "supabase/seed/seed.sql");
writeFileSync(out, lines.join("\n"));
console.log(`wrote ${out}`);
